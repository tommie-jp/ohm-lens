import type { ColorRun } from './runs.js';

/**
 * バンドの本数がカラーコードとして成立するか。
 *
 * IEC 60062 のカラーコードは 3〜6 本（温度係数つきで 7 本まで）。色を読む前に
 * 使える、色に依存しない規格の制約なので、検出枠が本体を捉えられているかの
 * 検算に使える。
 *
 * **間隔や幅の均一さは使わない。** 「等間隔らしさ」を採点する実装も試したが、
 * 実測では二度とも逆効果だった。
 *
 * - 枠を伸ばす基準にした場合 — 本体の一部しか覆っていない枠が背景の縞を
 *   拾って 0.80、正しい大きさの枠が 0.29。3 本だと間隔が 2 つしか取れず、
 *   まぐれで満点が出る
 * - 伸ばした結果の検算にした場合 — 07-10ohm-on-carpet の**正しい枠**を
 *   弾いた（比 3.69 → 1.75 に戻る）。カーペットの上ではバンドの切り出しが
 *   乱れ、正しい枠ほど不規則に見える
 *
 * 均一さが効くのは「バンドが正しく切り出せている」前提のときだけで、
 * それが崩れている画像を救う手段にはならなかった。
 */

/** カラーコードとして成立する本数の範囲。 */
export const MIN_BAND_COUNT = 3;
export const MAX_BAND_COUNT = 7;

/** 本数がカラーコードとして成立するか。 */
export function hasPlausibleBandCount(runs: readonly ColorRun[]): boolean {
  return runs.length >= MIN_BAND_COUNT && runs.length <= MAX_BAND_COUNT;
}
